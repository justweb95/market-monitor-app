// Mapa iz serbia-map.ts je linearno razvucena preko geografskog okvira Srbije
// (ekvidistantna cilindricna projekcija ispravljena za cos(sredisnje sirine)),
// pa se lat/lon prevodi u koordinate mape prostom linearnom transformacijom.
const LON_MIN = 18.8168;
const LON_MAX = 23.006;
const LAT_MIN = 41.8564;
const LAT_MAX = 46.1906;

/** Tacka na mapi (viewBox koordinate iz serbia-map.ts) za dati grad. */
export function projectToMap(
  lat: number,
  lon: number,
  mapWidth: number,
  mapHeight: number,
): { x: number; y: number } {
  return {
    x: ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * mapWidth,
    y: ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * mapHeight,
  };
}

/** Koliko jedinica mape ide na jedan kilometar (za crtanje kruga precnika). */
export function mapUnitsPerKm(mapHeight: number): number {
  const kmPerDegreeLat = 111.32;
  return mapHeight / ((LAT_MAX - LAT_MIN) * kmPerDegreeLat);
}
